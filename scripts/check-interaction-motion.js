  const pressed=await button.boundingBox();
  if(!(pressed.width<original.width*.99&&pressed.width>original.width*.94))throw Error('Missing proportional press feedback');
  if(Math.abs(pressed.width/original.width-pressed.height/original.height)>.015)throw Error('Control distorted during press');
  await page.mouse.up();
