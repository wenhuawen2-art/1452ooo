  await page.getByRole('button',{name:'我的',exact:true}).click();
  await page.locator('.pp-page').waitFor();
  await page.waitForTimeout(350);
  await page.screenshot({path:'output/playwright/motion-profile-393.png'});
  await page.goto('http://127.0.0.1:4193/app?mode=profile-design');
  await page.locator('.pp-trip').first().waitFor();
